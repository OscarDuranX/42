#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	c;

	if (nb >= 0 && nb <= 2147483647)
	{
		c = nb + '0';
		write(1, &c, 1);
		c = nb / 10 + '0';
		write(1, &c, 1);
		c = nb % 10 + '0';
		write(1, &c, 1);
		nb = nb % 10 + '0';
		c = nb / 10 + '0';
		write(1, &c, 1);
	}
	write(1, "\n", 1);
}

int	main(void)
{
	ft_putnbr (109);
	return (0);
}
